"""Build the production stylesheet without changing CSS cascade order.

Edit the five source files in assets/css, then run this script before release.
Use --check in verification to catch a stale generated file.
"""

from pathlib import Path
import argparse
import sys


ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("style.css", "books.css", "one.css", "system.css", "modern.css")
OUTPUT = ROOT / "assets" / "css" / "site.css"


def build() -> bytes:
    parts = [b"/* Generated by scripts/build_styles.py. Edit the source CSS files. */\n"]
    for name in SOURCES:
        source = ROOT / "assets" / "css" / name
        parts.extend((b"\n/* Source: " + name.encode("ascii") + b" */\n", source.read_bytes().rstrip() + b"\n"))
    return b"".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if site.css needs rebuilding")
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != expected:
            print("site.css is stale; run python scripts/build_styles.py", file=sys.stderr)
            return 1
        print("site.css matches the five source stylesheets")
        return 0
    OUTPUT.write_bytes(expected)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(expected)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
